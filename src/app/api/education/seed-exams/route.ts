export async function POST(request: NextRequest) {
    try {
        const app = await initAdmin();
        if (!app) return NextResponse.json({ error: 'Firebase not initialized' }, { status: 500 });

        const db = admin.firestore();
        const results: any[] = [];

        for (const examData of EXAM_DATA) {
            const now = admin.firestore.FieldValue.serverTimestamp();

            // Create the examSet document
            const examRef = await db.collection('examSets').add({
                ...examData.examSet,
                createdAt: now,
                updatedAt: now,
            });

            // Add questions as subcollection
            const batch = db.batch();
            for (const question of examData.questions) {
                const qRef = examRef.collection('questions').doc();
                batch.set(qRef, {
                    ...question,
                    createdAt: now,
                    updatedAt: now,
                });
            }
            await batch.commit();

            results.push({
                examId: examRef.id,
                title: examData.examSet.title,
                questionsCount: examData.questions.length,
                url: `/exams/${examRef.id}`,
            });
        }

        return NextResponse.json({
            success: true,
            message: `สร้างข้อสอบสำเร็จ ${results.length} ชุด`,
            exams: results,
        });
    } catch (error) {
        console.error('Error seeding exams:', error);
        return NextResponse.json({ error: 'Failed to seed exams' }, { status: 500 });
    }
}
